"""禁军军旗：原版 minimap_flag（13x16，青色和品红是王国色的遮罩）旗边镶金边、布面是深色加一颗金星。金色不在遮罩里，不随王国染色。
地方军直接用原版的旗。
用法: build.py 输出目录"""
import sys
from PIL import Image

C = {k: c for k, c in zip("0123456Gg", [(95, 65, 58), (127, 0, 127), (0, 188, 188), (53, 40, 40), (222, 0, 222),
                                         (0, 239, 239), (255, 0, 255), (255, 205, 60), (200, 140, 30)])}
GUARD = [
    ".............",
    ".............",
    "......0......",
    "..gGGGGGGGg..",
    "..G2222222G..",
    "...G22G22G...",
    "...G2GGG2G...",
    "...G22G22G...",
    "...G22222G...",
    "...g22222g...",
    "....g222g....",
    ".....ggg.....",
    "......3......",
    "......0......",
    ".............",
    ".............",
]
im = Image.new("RGBA", (13, 16))
for y, row in enumerate(GUARD):
    assert len(row) == 13
    for x, ch in enumerate(row):
        if ch != ".": im.putpixel((x, y), C[ch] + (255,))
im.save(f"{sys.argv[1]}/vd_flag_guard.png")
